def section_body(reason: str) -> str:
    """절 본문 마크다운(소제목 줄 빼고)"""
    if reason in VIRTUAL:
        return "\n".join([VIRTUAL_MARK, "", *(f"- {t}" for t in VIRTUAL[reason])])
    r = REAL[reason]
    parts = ["\n>\n".join(f"> {q}" for q in r.quote), f"출처: {r.source}"]
    if r.supplement:
        parts.append(f"병원 내부 보충: {r.supplement}")
    return "\n\n".join(parts)
